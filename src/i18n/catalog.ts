export type UiCatalog = typeof uiFi;

type Path<T> = T extends string ? never : {
  [K in keyof T & string]: T[K] extends string ? K : `${K}.${Path<T[K]>}`
}[keyof T & string];

export type MessageKey = Path<UiCatalog>;

function lookup(tree: Tree, path: string): string | undefined {
  const parts = path.split('.');
  let node: Leaf | Tree | undefined = tree;
  for (const part of parts) {
    if (!node || typeof node === 'string') return undefined;
    node = node[part];
  }
  return typeof node === 'string' ? node : undefined;
}

export function catalogFor(locale: Locale): UiCatalog {
  return (locale === 'en' ? uiEn : uiFi) as UiCatalog;
}

export function t(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  const template = lookup(catalogFor(locale) as Tree, key) || lookup(uiFi as Tree, key) || key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

export function formatDisplayDate(locale: Locale, iso: string): string {
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return iso;
  return new Intl.DateTimeFormat(locale === 'en' ? 'en-GB' : 'fi-FI', {
    dateStyle: 'medium',
    timeStyle: 'short'
  }).format(date);
}
